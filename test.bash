#!/bin/bash

ng () {                          # 関数ngの定義
        echo ${1}行目のテスト失敗   # $1はngの1番目の引数
        res=1                    # 追加: 失敗したことを記録
}

res=0                            # 0: 失敗なし（ngが呼ばれると1に[>
a=鈴木
[ "$a" = 鈴本 ] || ng "$LINENO"  # LINENOはこの行の行番号の入る変[>
[ "$a" = 鈴木 ] || ng "$LINENO"  # 失敗したら関数ngを呼び出す（$LI>

exit $res     # このシェルスクリプトの終了ステータスを返して終了#!>
